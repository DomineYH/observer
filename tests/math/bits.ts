// 결정적 수학 비트 출력 표: fixed inputs and their exact outputs, shared by the Node test and the engines page.
// Each row is [inputs, output] as f64 bits in hex. Outputs are the Node 24 (V8 13.6) built-in's values, an oracle
// independent of the port; every row matched the port, so no row carries a port-only value.
// A changed output changes every game result (ADR 0005): bump SIM_VERSION and regenerate the goldens.
// A new function gets its port and its rows in the slice that needs it.
const view = new DataView(new ArrayBuffer(8));

/** 16 lowercase hex digits of the f64 bits; every NaN is 'nan' (engines may differ in NaN payloads). */
export function toHex(x: number): string {
  if (x !== x) return 'nan';
  view.setFloat64(0, x);
  return view.getBigUint64(0).toString(16).padStart(16, '0');
}

export function fromHex(h: string): number {
  if (h === 'nan') return NaN;
  view.setBigUint64(0, BigInt('0x' + h));
  return view.getFloat64(0);
}

export const FNS = ['exp', 'log', 'sin', 'cos', 'tan', 'atan2'] as const;
export type Fn = (typeof FNS)[number];
type Row = [inputs: string[], out: string];

/** Each function's outputs for the table inputs, in table order. */
export function evaluate(fns: Record<Fn, (...args: number[]) => number>): Record<Fn, string[]> {
  const out = {} as Record<Fn, string[]>;
  for (const fn of FNS) out[fn] = BITS[fn].map(([inputs]) => toHex(fns[fn](...inputs.map(fromHex))));
  return out;
}

